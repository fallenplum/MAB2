"""Aggregate corrected deduplicated independent ARCC worker outputs.

This script is intentionally a direct result aggregator.  The fixed q=.9
radius is calibrated on the development split inside each worker file and
scored on its held-out split.  The old non-deduplicated worker results are
excluded because identical prompts could occupy different batch positions.
"""
from __future__ import annotations

import json
import re
import subprocess
from pathlib import Path

import numpy as np

import answer_region_only as aro


HERE = Path(__file__).resolve().parent
GOLD = HERE / "arcc_independent_gold.json"


def _label(path):
    stem = path.stem
    stem = stem.replace("arcc_", "").replace("_dedup", "")
    return stem


def _score_worker(worker):
    out = worker.with_name(worker.stem + "_score.json")
    cmd = [
        str(Path(r"D:\Anaconda\envs\tslib\python.exe")),
        str(HERE / "score_arcc_independent.py"),
        "--worker", str(worker), "--gold", str(GOLD), "--output", str(out),
    ]
    subprocess.run(cmd, check=True, cwd=str(HERE), capture_output=True, text=True)
    return json.loads(out.read_text(encoding="utf-8"))


def _answer_region(worker, mask):
    rows = aro.parse_rows(worker, GOLD)
    if mask == "all":
        for row in rows:
            row["changed_rows"] = [0, 1, 2, 3]
    calibration = [r for r in rows if int(r["key"][:8], 16) % 5 < 3]
    test = [r for r in rows if int(r["key"][:8], 16) % 5 == 4]
    return aro.score(test, aro.radii(calibration, 0.9))


def _mean(rows):
    keys = ("decision_exact", "answer_action_exact", "answer_accuracy", "tokens", "queries")
    return {key: float(np.mean([row[key] for row in rows])) for key in keys}


def main():
    workers = sorted(HERE.glob("arcc_*_dedup_*.jsonl"))
    workers = [p for p in workers if "_score" not in p.stem]
    if not workers:
        raise SystemExit("No deduplicated worker outputs found")
    cells = []
    for worker in workers:
        scored = _score_worker(worker)
        aggregate = scored["aggregate_corrected"]
        row = {
            "worker": worker.name,
            "cell": _label(worker),
            "n_rows": scored["n_rows"],
            "stale": aggregate["stale"],
            "tcr_guard": aggregate["tcr_guard"],
            "tcr_token": aggregate["tcr_token"],
            "cold_restart": aggregate["cold_restart"],
            "answer_region_changed_q09": _answer_region(worker, "changed"),
            "answer_region_all_q09": _answer_region(worker, "all"),
        }
        cells.append(row)
    methods = ("stale", "tcr_guard", "tcr_token", "cold_restart",
               "answer_region_changed_q09", "answer_region_all_q09")
    summary = {method: _mean([cell[method] for cell in cells]) for method in methods}
    result = {
        "schema": "arcc_independent_deduplicated_aggregate_v1",
        "worker_count": len(cells),
        "workers": [cell["worker"] for cell in cells],
        "cells": cells,
        "mean": summary,
        "interpretation": (
            "Only outputs generated by the deduplicated worker are included. "
            "Earlier non-deduplicated independent results are invalid for the "
            "final comparison because repeated prompts could be evaluated in "
            "different batch positions. q=.9 is fixed before test scoring."
        ),
    }
    out = HERE / "ARCC_INDEPENDENT_DEDUP_RESULTS.json"
    out.write_text(json.dumps(result, indent=2), encoding="utf-8")
    lines = [
        "# Independent deduplicated ARCC evidence",
        "",
        "Only the corrected deduplicated worker outputs are included. Earlier non-deduplicated outputs are excluded because repeated prompts could occupy different batch positions.",
        "",
        "## Aggregate",
        "",
        "| controller | decision exact | action exact | answer accuracy | relay tokens | queries |",
        "|---|---:|---:|---:|---:|---:|",
    ]
    labels = {
        "stale": "stale",
        "tcr_guard": "TCR guard",
        "tcr_token": "TCR token-aware",
        "cold_restart": "cold restart",
        "answer_region_changed_q09": "answer-region q=.9, changed rows",
        "answer_region_all_q09": "answer-region q=.9, all rows",
    }
    for method in methods:
        item = summary[method]
        lines.append("| {} | {:.4f} | {:.4f} | {:.4f} | {:.2f} | {:.3f} |".format(
            labels[method], item["decision_exact"], item["answer_action_exact"],
            item["answer_accuracy"], item["tokens"], item["queries"]))
    lines.extend(["", "## Cells", "", "| worker | stale action | TCR tokens | all-row action | all-row tokens |", "|---|---:|---:|---:|---:|"])
    for cell in cells:
        lines.append("| {} | {:.4f} | {:.2f} | {:.4f} | {:.2f} |".format(
            cell["cell"], cell["stale"]["answer_action_exact"], cell["tcr_guard"]["tokens"],
            cell["answer_region_all_q09"]["answer_action_exact"], cell["answer_region_all_q09"]["tokens"]))
    (HERE / "ARCC_INDEPENDENT_DEDUP_RESULTS.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(json.dumps(result, indent=2))


if __name__ == "__main__":
    main()

