from pathlib import Path
import hashlib,json
from datetime import datetime,timezone
root=Path('experiments/e0_real_workflow_20261126')
source_dir=root/'external/factscore_official/data/data/labeled'
selected=json.loads((root/'TOPIC_SELECTION_MANIFEST.json').read_text(encoding='utf-8'))
selected_ids={g['group_id'] for g in selected['groups']}
salt=selected['salt']
def read(path):
    out={}
    for i,line in enumerate(path.open(encoding='utf-8')):
        row=json.loads(line); topic=row['topic']; gid='e0g_'+hashlib.sha256((salt+'|'+topic).encode()).hexdigest()[:16]; out[gid]=(i,row)
    return out
old=read(source_dir/'InstructGPT.jsonl'); new=read(source_dir/'ChatGPT.jsonl')
missing=selected_ids-set(old)-set(new)
assert not missing, missing
pairs=[]
for gid in sorted(selected_ids):
    oi,orow=old[gid]; ni,nrow=new[gid]
    assert orow['topic']==nrow['topic']
    pairs.append({'group_id':gid,'topic_sha256':hashlib.sha256(orow['topic'].encode()).hexdigest(),'old_row_index':oi,'new_row_index':ni,'old_source':'InstructGPT','new_source':'ChatGPT','old_output_chars':len(orow.get('output','')),'new_output_chars':len(nrow.get('output',''))})
manifest={'schema':'mab2_e0_update_manifest_v1','status':'LOCKED_CONTROLLED_VERSION_UPDATE','update_family':'subject_generator_checkpoint_update','controlled_version_update':True,'reason':'No historical E0 deployment version was available. The official labeled release contains the same 183 topics generated by two documented source systems, enabling a predeclared paired update without using labels for selection.','old_version':{'source_model':'InstructGPT','file':'data/labeled/InstructGPT.jsonl','sha256':hashlib.sha256((source_dir/'InstructGPT.jsonl').read_bytes()).hexdigest()},'new_version':{'source_model':'ChatGPT','file':'data/labeled/ChatGPT.jsonl','sha256':hashlib.sha256((source_dir/'ChatGPT.jsonl').read_bytes()).hexdigest()},'pairing_rule':'same topic hash; groups fixed by TOPIC_SELECTION_MANIFEST.json; no gold/label filtering','group_count':len(pairs),'groups':pairs,'generated_at_utc':datetime.now(timezone.utc).isoformat()}
(root/'UPDATE_MANIFEST.json').write_text(json.dumps(manifest,ensure_ascii=False,indent=2)+'\n',encoding='utf-8')
print(json.dumps({'status':manifest['status'],'groups':len(pairs),'old_sha':manifest['old_version']['sha256'],'new_sha':manifest['new_version']['sha256']},ensure_ascii=False,indent=2))

